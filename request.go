package apptest

import (
	"bytes"
	"encoding/json"
	"io"
	"net/http"
	"net/http/httptest"
	"net/url"
	"strings"
)

// Request is a request under construction. Build it with the chainable
// methods, then Send.
type Request struct {
	app     *App
	method  string
	path    string
	header  http.Header
	body    io.Reader
	inertia bool
}

func (a *App) request(method, path string) *Request {
	return &Request{app: a, method: method, path: path, header: http.Header{}}
}

// JSON sets a JSON body and the matching Content-Type.
func (r *Request) JSON(body any) *Request {
	r.app.t.Helper()
	encoded, err := json.Marshal(body)
	if err != nil {
		r.app.t.Fatalf("apptest: encoding JSON body: %v", err)
	}
	r.body = bytes.NewReader(encoded)
	r.header.Set("Content-Type", "application/json")
	// Without this, a handler that content-negotiates would render HTML and
	// the test would be asserting against the wrong representation.
	r.header.Set("Accept", "application/json")
	return r
}

// Form sets a URL-encoded body and the matching Content-Type.
func (r *Request) Form(values map[string]string) *Request {
	form := url.Values{}
	for key, value := range values {
		form.Set(key, value)
	}
	r.body = strings.NewReader(form.Encode())
	r.header.Set("Content-Type", "application/x-www-form-urlencoded")
	return r
}

// Raw sets the body bytes verbatim, leaving the Content-Type to the caller.
//
// It is what a multipart upload needs: the boundary is part of the
// Content-Type and is generated by multipart.Writer, so neither JSON nor Form
// can express one. Pair it with Header("Content-Type", writer.FormDataContentType()).
func (r *Request) Raw(body []byte) *Request {
	r.body = bytes.NewReader(body)
	return r
}

// Header sets one request header.
func (r *Request) Header(key, value string) *Request {
	r.header.Set(key, value)
	return r
}

// Inertia marks the request as an Inertia XHR, so the response is page JSON
// rather than a document. Use it for what the client does after the first
// load; use a plain Get to assert on the server-rendered document.
//
// It also sends the application's current asset version. That is not
// optional: Inertia's version protocol answers 409 Conflict whenever the
// version a client sends differs from the server's, and a request sending
// none differs from any non-empty version. An application that hashes its
// Vite manifest — which is the default — would therefore answer 409 to every
// Inertia request a test made, and the test would be asserting on an empty
// body.
//
// The version is discovered once per App and cached: see inertiaVersion.
func (r *Request) Inertia() *Request {
	r.header.Set("X-Inertia", "true")
	r.header.Set("X-Requested-With", "XMLHttpRequest")
	r.header.Set("Accept", "text/html, application/xhtml+xml")
	r.inertia = true
	return r
}

// InertiaVersion overrides the asset version sent with an Inertia request,
// for a test that is deliberately exercising the mismatch.
func (r *Request) InertiaVersion(version string) *Request {
	r.header.Set("X-Inertia-Version", version)
	r.inertia = false // an explicit version is not overwritten
	return r
}

// ActingAs authenticates the request as the user with this id.
//
// It establishes a verified subject and lets the application's own UserLoader
// resolve it, so the handler receives the concrete type it would in
// production. That is the whole point: a stubbed user would make a test of
// auth.UserAs[*models.User] prove nothing.
//
// The id is the one UserProvider.GetID returns — a string, even when the
// column is an integer.
func (r *Request) ActingAs(id string) *Request {
	r.header.Set(actingAsHeader, id)
	return r
}

// Send performs the request and returns the response.
//
// Cookies are carried across requests on one App, so a login followed by a
// page load behaves as a browser would, and a CSRF token issued by one
// request is still valid for the next.
func (r *Request) Send() *Response {
	r.app.t.Helper()

	target := r.app.baseURL.ResolveReference(&url.URL{Path: r.path})
	if idx := strings.IndexByte(r.path, '?'); idx >= 0 {
		target = r.app.baseURL.ResolveReference(&url.URL{
			Path:     r.path[:idx],
			RawQuery: r.path[idx+1:],
		})
	}

	r.attachCSRF(target)

	if r.inertia && r.header.Get("X-Inertia-Version") == "" {
		r.header.Set("X-Inertia-Version", r.app.inertiaVersion())
	}

	// httptest.NewRequest panics on a path it cannot parse, which surfaces as a
	// stack trace in the middle of a test run with no indication of which
	// request caused it. A malformed path is almost always a typo in the test —
	// an unencoded space, usually — so it is reported as one.
	if _, err := http.NewRequest(r.method, target.String(), nil); err != nil {
		r.app.t.Fatalf("apptest: %s %s is not a valid request: %v\n\t"+
			"an unencoded space or control character in the path is the usual cause",
			r.method, r.path, err)
	}

	request := httptest.NewRequest(r.method, target.String(), r.body)
	for key, values := range r.header {
		for _, value := range values {
			request.Header.Add(key, value)
		}
	}
	for _, cookie := range r.app.jar.Cookies(target) {
		request.AddCookie(cookie)
	}

	recorder := httptest.NewRecorder()
	r.app.handler.ServeHTTP(recorder, request)

	result := recorder.Result()
	body, err := io.ReadAll(result.Body)
	if err != nil {
		r.app.t.Fatalf("apptest: reading response body: %v", err)
	}
	result.Body.Close()

	if cookies := result.Cookies(); len(cookies) > 0 {
		r.app.jar.SetCookies(target, cookies)
	}

	return &Response{t: r.app.t, Response: result, Body: body, request: request}
}
